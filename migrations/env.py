"""Alembic runtime environment.

Two things here are specific to running against Supabase:

* Migrations connect through the *direct* endpoint (port 5432) when
  ``DATABASE_DIRECT_URL`` is set. DDL and the migration advisory lock need a
  stable session, which a transaction-mode pooler cannot promise.
* A Supabase database contains schemas and extension-owned tables we do not
  manage (``auth``, ``storage``, ``extensions``, ...). ``include_object``
  below stops autogenerate from proposing to drop any of them.
"""

from __future__ import annotations

import asyncio
import sys
from logging.config import fileConfig
from typing import Any

if sys.platform == "win32":
    # psycopg's async driver cannot drive Windows' default ProactorEventLoop;
    # it needs a selector loop. Set before any loop is created, which on this
    # path means before asyncio.run() in run_migrations_online().
    asyncio.set_event_loop_policy(asyncio.WindowsSelectorEventLoopPolicy())

from alembic import context
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

from app.core.config import get_settings

# Importing the models package registers every table on Base.metadata.
# Without it autogenerate would see an empty model set and emit drops.
from app.db.models import Base

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

settings = get_settings()

# configparser treats '%' as interpolation syntax, and generated database
# passwords regularly contain one. Escaping here avoids a confusing
# InterpolationSyntaxError at connect time.
config.set_main_option("sqlalchemy.url", settings.migration_database_url.replace("%", "%%"))

target_metadata = Base.metadata

# Schemas owned by Supabase itself; never reflected, never modified.
EXTERNAL_SCHEMAS = frozenset(
    {
        "auth",
        "storage",
        "realtime",
        "graphql",
        "graphql_public",
        "extensions",
        "vault",
        "pgsodium",
    }
)


def include_object(
    obj: Any,
    name: str | None,
    type_: str,
    reflected: bool,
    compare_to: Any,
) -> bool:
    """Restrict autogenerate to tables this project owns.

    A reflected table that is absent from ``target_metadata`` belongs to
    Supabase or to an extension, so it is excluded: otherwise the first
    autogenerated revision would cheerfully drop the auth schema.
    """
    if getattr(obj, "schema", None) in EXTERNAL_SCHEMAS:
        return False
    if type_ == "table" and reflected:
        return name in target_metadata.tables
    return True


def _configure(**extra: Any) -> None:
    context.configure(
        target_metadata=target_metadata,
        include_object=include_object,
        include_schemas=False,
        # Detect column type and server-default changes, which Alembic
        # ignores by default and which are a common source of drift.
        compare_type=True,
        compare_server_default=True,
        # Emit constraint names from the metadata naming convention so a
        # downgrade can drop what the upgrade created.
        render_as_batch=False,
        **extra,
    )


def run_migrations_offline() -> None:
    """Render migrations as SQL without connecting (``alembic ... --sql``)."""
    _configure(
        url=config.get_main_option("sqlalchemy.url"),
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )

    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    _configure(connection=connection)

    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    """Open a short-lived connection and run migrations on it."""
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        # One connection, closed immediately afterwards: a migration run is
        # not a long-lived application process.
        poolclass=pool.NullPool,
    )

    async with connectable.connect() as connection:
        await connection.run_sync(do_run_migrations)

    await connectable.dispose()


def run_migrations_online() -> None:
    asyncio.run(run_async_migrations())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()

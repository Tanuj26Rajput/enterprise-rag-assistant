"""Declarative base and shared column mixins.

The naming convention is deliberate: PostgreSQL happily auto-names indexes and
constraints, but Alembic can only emit a reliable ``DROP CONSTRAINT`` if the
name is deterministic. Fixing the convention here means every migration -
including autogenerated ones - refers to constraints by a name we control.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import DateTime, MetaData, Uuid, func, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# `column_0_N_name` expands to every column in the constraint, so composite
# constraints also get stable names. Keep table/column names short enough that
# the result stays under PostgreSQL's 63-character identifier limit.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Base class for every ORM model."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    # Maps bare Python annotations to PostgreSQL types so models can be written
    # as `Mapped[datetime]` / `Mapped[dict[str, Any]]` without repeating types.
    type_annotation_map = {
        uuid.UUID: Uuid(as_uuid=True),
        datetime: DateTime(timezone=True),
        dict[str, Any]: JSONB,
        list[dict[str, Any]]: JSONB,
    }

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        identifier = getattr(self, "id", None)
        return f"<{type(self).__name__} id={identifier}>"


class UUIDPrimaryKeyMixin:
    """Surrogate UUID primary key.

    UUIDs let the API expose identifiers that leak no row counts and let the
    ingestion pipeline mint document and chunk ids before they are persisted.
    The server-side default keeps rows valid for inserts made outside the ORM
    (migrations, psql, Supabase dashboard).
    """

    # Declarative appends mixin columns after the model's own; sort_order
    # overrides that so every table reads id, <payload>, <timestamps>.
    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        server_default=text("gen_random_uuid()"),
        sort_order=-100,
    )


class TimestampMixin:
    """``created_at`` / ``updated_at`` maintained by the database clock."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        index=True,
        sort_order=100,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
        sort_order=101,
    )


class SoftDeleteMixin:
    """Soft deletion for tenant-visible records.

    Documents and conversations are referenced by citations and audit entries,
    so they are retired by stamping ``deleted_at`` rather than being removed.
    """

    deleted_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        index=True,
        sort_order=102,
    )

    @property
    def is_deleted(self) -> bool:
        return self.deleted_at is not None
